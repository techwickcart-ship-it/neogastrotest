/**
 * Checks if the given URL is a cartoon avatar (e.g., dicebear)
 */
export function isCartoonAvatar(url: string | null | undefined): boolean {
  if (!url) return false;
  const str = String(url).toLowerCase();
  return str.includes('dicebear.com') || str.includes('multiavatar.com') || str.includes('avataaars') || str.includes('api.dicebear');
}

/**
 * Resolves an authentic, real professional photo for any doctor or staff member.
 * If the user has uploaded an actual photo (Base64 data:image or custom URL), it is preserved.
 * If the avatar is missing or a cartoon avatar, a real medical professional photo is returned.
 */
export function getStaffPhotoUrl(staffOrUser: any): string {
  if (!staffOrUser) {
    return DOCTOR_MALE_POOL[0];
  }

  const rawAvatar = typeof staffOrUser === 'string' ? staffOrUser : (staffOrUser.avatar_url || staffOrUser.avatar || staffOrUser.photo || '');
  const staffName = (typeof staffOrUser === 'object' ? (staffOrUser.name || staffOrUser.fullName || '') : '').trim();
  const staffRole = (typeof staffOrUser === 'object' ? String(staffOrUser.role || staffOrUser.designation || '').toUpperCase() : '').trim();
  const staffDept = (typeof staffOrUser === 'object' ? String(staffOrUser.department || staffOrUser.specialization || staffOrUser.specialty || '').toLowerCase() : '').trim();

  // If a valid real photo URL or base64 data image is present and NOT a cartoon
  if (rawAvatar && typeof rawAvatar === 'string' && !isCartoonAvatar(rawAvatar)) {
    if (rawAvatar.startsWith('data:image/') || rawAvatar.startsWith('blob:') || rawAvatar.startsWith('http://') || rawAvatar.startsWith('https://')) {
      return rawAvatar;
    }
  }

  // Check known doctors and staff by exact name
  if (staffName && REAL_DOCTOR_PHOTOS[staffName]) {
    return REAL_DOCTOR_PHOTOS[staffName];
  }

  // Check partial name match
  for (const [key, photo] of Object.entries(REAL_DOCTOR_PHOTOS)) {
    if (staffName && (staffName.toLowerCase().includes(key.toLowerCase()) || key.toLowerCase().includes(staffName.toLowerCase()))) {
      return photo;
    }
  }

  // Hash code based on name for consistent assignment
  let hash = 0;
  for (let i = 0; i < staffName.length; i++) {
    hash = staffName.charCodeAt(i) + ((hash << 5) - hash);
  }
  const positiveHash = Math.abs(hash);

  // Female name heuristics for realistic photo pairing
  const femaleKeywords = ['dr. priya', 'dr. ananya', 'dr. sunita', 'sister', 'nurse', 'priya', 'sunita', 'ananya', 'pooja', 'neha', 'anjali', 'shreya', 'dr. meena', 'dr. kavita'];
  const isFemale = femaleKeywords.some(kw => staffName.toLowerCase().includes(kw));

  if (staffRole.includes('NURSE') || staffDept.includes('nursing')) {
    return NURSE_POOL[positiveHash % NURSE_POOL.length];
  }

  if (staffRole.includes('LAB') || staffRole.includes('PATH') || staffDept.includes('lab') || staffDept.includes('pathology')) {
    return LAB_TECH_POOL[positiveHash % LAB_TECH_POOL.length];
  }

  if (staffRole.includes('RECEPT') || staffRole.includes('ACCOUNT') || staffRole.includes('FRONT') || staffRole.includes('FINANCE')) {
    return ADMIN_STAFF_POOL[positiveHash % ADMIN_STAFF_POOL.length];
  }

  if (isFemale) {
    return DOCTOR_FEMALE_POOL[positiveHash % DOCTOR_FEMALE_POOL.length];
  }

  return DOCTOR_MALE_POOL[positiveHash % DOCTOR_MALE_POOL.length];
}
