export const PATHOLOGY_REFERENCE_RANGES: AgeGenderReferenceRange[] = PATHOLOGY_TEST_DATA
  .filter(t => t.referenceRange && t.referenceRange !== '—' && t.referenceRange !== 'Descriptive')
  .map((t, idx) => {
    let low = 0;
    let high = 100;
    const cleanRange = t.referenceRange.replace(/[^0-9.–-]/g, ' ').trim();
    const parts = cleanRange.split(/[–-]/).map(p => parseFloat(p.trim())).filter(n => !isNaN(n));
    if (parts.length >= 2) {
      low = parts[0];
      high = parts[1];
    } else if (parts.length === 1) {
      high = parts[0];
    }

    return {
      id: `RNG-${t.code}-${idx}`,
      parameterId: `PAR-${t.code}`,
      gender: t.referenceRange.includes('M:') ? 'Male' : 'All',
      ageGroup: 'Adult',
      lowRange: low,
      highRange: high,
      unit: t.unit !== '—' ? t.unit : ''
    };
  });
