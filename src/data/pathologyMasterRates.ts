// Clean vial formatter
export const formatVialLabel = (rawVial?: string): string => {
  if (!rawVial || rawVial === '.' || rawVial === '…') return 'SST / Plain';
  const v = rawVial.trim().toUpperCase();
  if (v === 'EDTA' || v === 'EDTS') return 'EDTA (Lavender)';
  if (v === 'PLAIN') return 'Plain Clot (Red)';
  if (v === 'FLU' || v === 'FLU.') return 'Sodium Fluoride (Grey)';
  if (v === 'CON' || v === 'CON.') return 'Sterile Container (CON)';
  if (v === 'STC' || v === 'STC.' || v === 'CITRATED') return 'Sodium Citrate (Blue)';
  if (v === 'HEP.' || v === 'HEPARIN') return 'Heparin (Green)';
  if (v === 'SWAB' || v === 'SWAB.') return 'Sterile Swab';
  if (v === 'SLIDE') return 'Glass Slide';
  if (v === 'CAPILLARY TUBE') return 'Capillary Tube';
  if (v === 'EDTA/PLAIN') return 'EDTA / Plain';
  return rawVial.trim();
};

