export const RADIOLOGY_MASTER_INVESTIGATIONS: InvestigationTest[] = RADIOLOGY_TEST_DATA.map((t) => {
  let catId = 'CAT-RAD-XR';
  let subCatId = 'SUB-XR-CHEST';

  if (t.modality === 'X-Ray') {
    catId = 'CAT-RAD-XR';
    if (t.subCategory.includes('Spine')) subCatId = 'SUB-XR-SPINE';
    else if (t.subCategory.includes('Abdomen')) subCatId = 'SUB-XR-ABD';
    else if (t.subCategory.includes('Extremities')) subCatId = 'SUB-XR-EXTR';
    else if (t.subCategory.includes('Skull')) subCatId = 'SUB-XR-SKULL';
    else subCatId = 'SUB-XR-CHEST';
  } else if (t.modality === 'Ultrasound') {
    catId = 'CAT-RAD-USG';
    if (t.subCategory.includes('Obstetric')) subCatId = 'SUB-USG-OBS';
    else if (t.subCategory.includes('Pelvic')) subCatId = 'SUB-USG-GYN';
    else if (t.subCategory.includes('Small Parts')) subCatId = 'SUB-USG-PART';
    else if (t.subCategory.includes('Musculoskeletal')) subCatId = 'SUB-USG-MSK';
    else subCatId = 'SUB-USG-ABD';
  } else if (t.modality === 'Doppler') {
    catId = 'CAT-RAD-DOP';
    if (t.subCategory.includes('Visceral')) subCatId = 'SUB-DOP-VISC';
    else if (t.subCategory.includes('Obstetric')) subCatId = 'SUB-DOP-OBS';
    else subCatId = 'SUB-DOP-PERIPH';
  } else if (t.modality === 'CT Scan') {
    catId = 'CAT-RAD-CT';
    if (t.subCategory.includes('Neuro')) subCatId = 'SUB-CT-NEURO';
    else if (t.subCategory.includes('Thoracic')) subCatId = 'SUB-CT-CHEST';
    else if (t.subCategory.includes('Angiography')) subCatId = 'SUB-CT-ANGIO';
    else if (t.subCategory.includes('Spine')) subCatId = 'SUB-CT-SPINE';
    else subCatId = 'SUB-CT-BODY';
  } else if (t.modality === 'MRI') {
    catId = 'CAT-RAD-MRI';
    if (t.subCategory.includes('Neuro')) subCatId = 'SUB-MRI-NEURO';
    else if (t.subCategory.includes('Spine')) subCatId = 'SUB-MRI-SPINE';
    else if (t.subCategory.includes('Musculoskeletal')) subCatId = 'SUB-MRI-MSK';
    else subCatId = 'SUB-MRI-BODY';
  } else if (t.modality === 'Fluoroscopy' || t.modality === 'Fibroscan') {
    catId = 'CAT-RAD-SPEC';
    subCatId = t.modality === 'Fibroscan' ? 'SUB-SPEC-FIBRO' : 'SUB-SPEC-GI';
  } else if (t.modality === 'Mammography' || t.modality === 'DEXA') {
    catId = 'CAT-RAD-MAM';
    subCatId = t.modality === 'Mammography' ? 'SUB-MAM-BREAST' : 'SUB-DEXA-BMD';
  } else if (t.modality === 'Interventional') {
    catId = 'CAT-RAD-IR';
    subCatId = 'SUB-IR-PROC';
  }

  return {
    code: t.code,
    name: t.name,
    shortName: t.shortName,
    department: 'Radiology',
    categoryId: catId,
    category: t.category,
    subCategoryId: subCatId,
    subCategory: t.subCategory,
    specimen: 'Radiological Imaging',
    sampleType: t.equipment,
    container: t.modality,
    vial: t.modality,
    method: `${t.modality} Protocol (${t.contrast})`,
    unit: undefined,
    referenceRange: t.preparation,
    machineName: t.equipment,
    reportType: (t.reportType as any) || 'Descriptive',
    tat: t.tat,
    normalRangeApplicable: false,
    criticalValueApplicable: true,
    nablCompliance: true,
    activeStatus: 'Active' as const,
    billingCategory: t.billingCategory,
    nablDiscipline: 'Diagnostic Radiology & Imaging',
    nablStatus: 'Scope-Specific / AERB Certified',
    nablScopeMapping: 'Standard Medical Diagnostic Imaging Scope',
    price: t.price
  };
});

